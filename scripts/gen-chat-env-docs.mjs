#!/usr/bin/env node
// Generate the chat's env-var docs from packages/chat/src/app/envVars.ts —
// the single source of truth. Renders the three places that used to be
// hand-maintained (and had drifted apart: env.d.ts and the README both lost
// VITE_UDI_REMOTE_PACKAGE, and the README cited a deleted module):
//
//   packages/chat/.env.example     — the whole file
//   packages/chat/README.md        — the table between the generated markers
//   packages/chat/src/env.d.ts     — the ImportMetaEnv interface
//
// Also verifies the reverse direction: every VITE_* actually read in the
// source must be declared in envVars.ts, so a new var can't be added without
// being documented.
//
//   node scripts/gen-chat-env-docs.mjs           # write
//   node scripts/gen-chat-env-docs.mjs --check   # exit 1 if stale (CI)
import { readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const abs = (p) => fileURLToPath(new URL(`../${p}`, import.meta.url));

const { ENV_VARS } = await import(abs('packages/chat/src/app/envVars.ts'));

const BEGIN = '<!-- BEGIN generated: env vars (scripts/gen-chat-env-docs.mjs) -->';
const END = '<!-- END generated: env vars -->';

const HEADER = `\
# Generated by scripts/gen-chat-env-docs.mjs from src/app/envVars.ts —
# do not edit by hand. Describe a variable there and regenerate.
#
# Copy to .env.local to override (scripts/setup.mjs does this for you). Every
# variable is optional; the values shown are the defaults.
`;

/** Wrap prose to `width`, keeping markdown backtick spans intact. */
function wrap(text, width) {
  const lines = [];
  let line = '';
  for (const word of text.split(/\s+/)) {
    if (line && line.length + 1 + word.length > width) {
      lines.push(line);
      line = word;
    } else {
      line = line ? `${line} ${word}` : word;
    }
  }
  if (line) lines.push(line);
  return lines;
}

function renderExample() {
  let out = HEADER;
  for (const { name, docDefault, example, template, description } of ENV_VARS) {
    out += '\n';
    for (const line of wrap(description, 76)) out += `# ${line}\n`;
    // A var with `template` is left live so `.env.local` actually sets it;
    // the rest are commented, documenting without overriding any default.
    out += template === undefined
      ? `# ${name}=${example ?? docDefault ?? ''}\n`
      : `${name}=${template}\n`;
  }
  return out;
}

/**
 * Emit the column padding prettier would apply anyway — otherwise the commit
 * hook reformats the table and the --check below immediately reports drift.
 */
function markdownTable(header, rows) {
  const widths = header.map((_, i) =>
    Math.max(header[i].length, ...rows.map((r) => r[i].length)),
  );
  const line = (cells) => `| ${cells.map((c, i) => c.padEnd(widths[i])).join(' | ')} |`;
  return [line(header), line(widths.map((w) => '-'.repeat(w))), ...rows.map(line)].join('\n');
}

function renderTable() {
  return markdownTable(
    ['Variable', 'Default', 'Description'],
    ENV_VARS.map(({ name, docDefault, description }) => [
      `\`${name}\``,
      docDefault ? `\`${docDefault}\`` : '—',
      description.replace(/\|/g, '\\|'),
    ]),
  );
}

function renderEnvDts() {
  let out = `\
/// <reference types="vite/client" />

// Generated by scripts/gen-chat-env-docs.mjs from src/app/envVars.ts —
// do not edit by hand. Describe a variable there and regenerate.

interface ImportMetaEnv {
`;
  for (const { name, description } of ENV_VARS) {
    out += '  /**\n';
    for (const line of wrap(description, 72)) out += `   * ${line}\n`;
    out += `   */\n  readonly ${name}?: string;\n`;
  }
  out += `}

interface ImportMeta {
  readonly env: ImportMetaEnv;
}
`;
  return out;
}

function splice(text, table) {
  const start = text.indexOf(BEGIN);
  const end = text.indexOf(END);
  if (start === -1 || end === -1) {
    throw new Error(`missing ${BEGIN} / ${END} markers`);
  }
  return `${text.slice(0, start + BEGIN.length)}\n\n${table}\n\n${text.slice(end)}`;
}

/** Every VITE_* read in the source, so a new one can't go undocumented. */
function varsReadInSource() {
  const found = new Set();
  const walk = (dir) => {
    for (const entry of readdirSync(dir)) {
      if (entry === 'node_modules' || entry === 'dist') continue;
      const path = `${dir}/${entry}`;
      if (statSync(path).isDirectory()) walk(path);
      else if (/\.(ts|tsx|mts)$/.test(entry) && !path.endsWith('envVars.ts')) {
        const text = readFileSync(path, 'utf8');
        for (const [, name] of text.matchAll(/(?:import\.meta|process)\.env\.(VITE_\w+)/g)) {
          found.add(name);
        }
      }
    }
  };
  walk(abs('packages/chat/src'));
  // VITE_BASE is read at build time from vite.config.ts, not from src.
  const config = readFileSync(abs('packages/chat/vite.config.ts'), 'utf8');
  for (const [, name] of config.matchAll(/(?:import\.meta|process)\.env\.(VITE_\w+)/g)) {
    found.add(name);
  }
  return found;
}

const check = process.argv.includes('--check');
const declared = new Set(ENV_VARS.map((v) => v.name));
const undeclared = [...varsReadInSource()].filter((name) => !declared.has(name));

const outputs = {
  'packages/chat/.env.example': renderExample(),
  'packages/chat/src/env.d.ts': renderEnvDts(),
  'packages/chat/README.md': splice(readFileSync(abs('packages/chat/README.md'), 'utf8'), renderTable()),
};

const stale = Object.entries(outputs).filter(
  ([path, content]) => readFileSync(abs(path), 'utf8') !== content,
);

if (check) {
  for (const name of undeclared) {
    console.error(`undocumented env var read in source: ${name} — add it to src/app/envVars.ts`);
  }
  for (const [path] of stale) console.error(`out of date: ${path}`);
  if (stale.length || undeclared.length) {
    console.error('\nenvVars.ts changed without regenerating. Run:\n  node scripts/gen-chat-env-docs.mjs');
    process.exit(1);
  }
  console.log('chat env docs are up to date');
} else {
  if (undeclared.length) {
    console.error(`undocumented env vars read in source: ${undeclared.join(', ')}`);
    process.exit(1);
  }
  for (const [path, content] of stale) {
    writeFileSync(abs(path), content);
    console.log(`wrote ${path}`);
  }
  if (!stale.length) console.log('chat env docs already up to date');
}
