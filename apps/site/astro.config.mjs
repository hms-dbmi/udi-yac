// Served at https://hms-dbmi.github.io/udi-yac/. Besides the docs, the site
// serves the chat at app/ (src/pages/app, embedding the udi-yac library) and the
// grammar editor at grammar/editor/ (src/pages/grammar). Starlight does not add
// `base` to links written in markdown, so links in the content spell out
// /udi-yac/.

/** GitHub Pages redirects /udi-yac/app to /udi-yac/app/. In dev the app page
 *  would be served without the slash, resolving the chat's page-relative data
 *  paths one level too high. */
/** @type {import('vite').Plugin} */
const devTrailingSlash = {
  name: 'udi-yac-dev-trailing-slash',
  configureServer(server) {
    server.middlewares.use((req, res, next) => {
      const match = req.url?.match(/^\/(?:udi-yac\/)?app(\?.*)?$/);
      if (!match) return next();
      res.writeHead(301, { Location: `/udi-yac/app/${match[1] ?? ''}` }).end();
    });
  },
};

